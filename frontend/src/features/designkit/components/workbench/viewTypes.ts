/**
 * 工作台内部几个组件之间传来传去的小类型。
 *
 * 单独一个文件是因为 `<script setup>` 里不能写 `export`——
 * 组件之间要共用的类型只能放在普通 .ts 里。
 */

/**
 * 工作台四步标题前那个编号圆点的状态（设计稿 05-视觉精修 第③块）。
 *
 * 由页面层从已有状态推导后传给各步组件：
 * 有图=步1完成、有词=步2完成、选了比例=步3完成、三样齐=步4高亮；
 * 「当前步」= 第一个没完成的那步。组件自己不判断，只照着画。
 */
export type WorkbenchStepState = 'todo' | 'current' | 'done'

/** 提交失败时要显示的三样东西。 */
export interface SubmitErrorView {
  /** 中文整句（已含错误码），直接上屏。 */
  text: string
  /** 后端的排障编号；有就显示出来，运营截图给管理员能直接查。 */
  requestId: string | null
  /**
   * 要不要在错误下面给一个「申请额度」按钮。
   *
   * 余额不足时**必须**给（决策 19）：充值和兑换码菜单对运营是隐藏的，
   * 只说「余额不足」等于把人堵死。
   */
  showQuota: boolean
}
